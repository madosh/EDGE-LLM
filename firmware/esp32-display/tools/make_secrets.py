#!/usr/bin/env python3
"""Write include/secrets.h for the ESP32 status display.

Reads the device's certificate directory (ca.crt, device.crt, device.key, as
issued by scripts/gen-certs.sh) and the Wi-Fi and control-plane settings, and
writes them into one header the firmware compiles in. The output holds the
Wi-Fi password and the device's private key, so it is git-ignored.

    python tools/make_secrets.py --certs certs --ssid MyWifi --password secret \
        --address 192.168.1.20 --name esp32-display-1
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
NAME_RE = re.compile(r"^[A-Za-z0-9._-]+$")  # what gen-certs.sh accepts


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_pem(path: pathlib.Path, marker: str) -> str:
    try:
        text = path.read_text(encoding="ascii").replace("\r\n", "\n").strip() + "\n"
    except FileNotFoundError:
        sys.exit(f"missing {path}: copy the device's certificate directory first (docs/esp32-display.md, step 2)")
    if f"-----BEGIN {marker}" not in text:
        sys.exit(f"{path} does not look like a PEM {marker.lower()}")
    if ")PEM" in text:
        sys.exit(f"{path} contains ')PEM', which would end the raw string early")
    return text


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--certs", required=True, type=pathlib.Path, help="directory with ca.crt, device.crt, device.key")
    p.add_argument("--ssid", required=True, help="Wi-Fi network (2.4 GHz)")
    p.add_argument("--password", required=True, help="Wi-Fi password")
    p.add_argument("--address", required=True, help="LAN IP or hostname of the control-plane host")
    p.add_argument("--name", default="esp32-display-1", help="device name = the certificate's common name")
    p.add_argument("--labels", default="location=desk,type=esp32-display", help="key=value,key=value")
    p.add_argument("--port", type=int, default=8443, help="device HTTPS API port")
    p.add_argument("--tls-name", default="control-plane", help="DNS name in the server certificate")
    p.add_argument("--out", type=pathlib.Path, default=ROOT / "include" / "secrets.h")
    args = p.parse_args()

    if not NAME_RE.match(args.name):
        sys.exit(f"invalid device name {args.name!r}: use letters, digits, '.', '_' or '-'")
    for pair in filter(None, args.labels.split(",")):
        if "=" not in pair:
            sys.exit(f"invalid label {pair!r}: expected key=value")

    ca = read_pem(args.certs / "ca.crt", "CERTIFICATE")
    cert = read_pem(args.certs / "device.crt", "CERTIFICATE")
    key = read_pem(args.certs / "device.key", "")  # PRIVATE KEY or RSA PRIVATE KEY

    header = f"""// Generated by tools/make_secrets.py. Holds the Wi-Fi password and this
// device's private key: do not commit it (it is git-ignored).
#pragma once

#define WIFI_SSID {c_string(args.ssid)}
#define WIFI_PASSWORD {c_string(args.password)}

#define CP_ADDRESS {c_string(args.address)}
#define CP_PORT {args.port}
#define CP_TLS_NAME {c_string(args.tls_name)}

#define DEVICE_NAME {c_string(args.name)}
#define DEVICE_LABELS {c_string(args.labels)}

static const char CA_CERT[] = R"PEM({ca})PEM";

static const char DEVICE_CERT[] = R"PEM({cert})PEM";

static const char DEVICE_KEY[] = R"PEM({key})PEM";
"""
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(header, encoding="ascii", newline="\n")
    print(f"wrote {args.out} for {args.name} -> {args.address}:{args.port}")


if __name__ == "__main__":
    main()
